// Writes src/github_slugger.rs: the characters github-slugger removes from a heading's text, as
// sorted ranges, so `headingIds: "github"` gives its ids exactly. github-slugger is what
// rehype-slug uses, and so Astro, VitePress, Docusaurus and every remark/rehype site's anchors.
//
//     node crates/ssqch-markdown/scripts/github-slugger-table.mjs <github-slugger folder>
//
// (It isn't a dependency of ssqch: point it at any install of it, `npm pack github-slugger@2.0.0`.)
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const from = process.argv[2];
if (!from) { process.stderr.write("usage: node github-slugger-table.mjs <github-slugger folder>\n"); process.exit(2); }
const { version } = JSON.parse(fs.readFileSync(path.join(from, "package.json"), "utf8"));
const { regex } = await import(pathToFileURL(path.join(from, "regex.js")).href);
const removed = new RegExp(regex.source, "u");
const ranges = [];
for (let cp = 0; cp <= 0x10ffff; cp++) {
	if (cp >= 0xd800 && cp <= 0xdfff) continue;
	if (!removed.test(String.fromCodePoint(cp))) continue;
	const last = ranges[ranges.length - 1];
	if (last && last[1] === cp - 1) last[1] = cp;
	else ranges.push([cp, cp]);
}
const hex = (n) => `0x${n.toString(16).toUpperCase()}`;
const out = `// Generated by scripts/github-slugger-table.mjs from github-slugger ${version}: the characters it
// removes from a heading's text (its regex.js), as sorted ranges. Don't edit by hand.

/// Whether github-slugger ${version} removes \`c\` from a heading's text.
pub fn removes(c: char) -> bool {
    let cp = c as u32;
    REMOVED.binary_search_by(|&(low, high)| if high < cp { std::cmp::Ordering::Less } else if low > cp { std::cmp::Ordering::Greater } else { std::cmp::Ordering::Equal }).is_ok()
}

const REMOVED: &[(u32, u32)] = &[
${ranges.map(([a, b]) => `    (${hex(a)}, ${hex(b)}),`).join("\n")}
];
`;
const target = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../src/github_slugger.rs");
fs.writeFileSync(target, out);
process.stdout.write(`${target}: ${ranges.length} ranges from github-slugger ${version}\n`);
