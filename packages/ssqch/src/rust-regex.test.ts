/** What `ssqch diff --ignore` compares: the text without CRLF and without the pattern's matches. */
const same = (re: RegExp, a: string, b: string) => {
	const strip = (t: string) => t.replaceAll("\r\n", "\n").replace(re, "");
	return strip(a) === strip(b);
};

test("patterns the crate refused are refused in its words", () => {
	for (const [pattern, error] of ERRORS) {
		assert.throws(() => rustRegExp(pattern), (e: unknown) => e instanceof RegexError && e.message === error, pattern);
	}
});

test("patterns the crate took are taken", () => {
	for (const pattern of ACCEPTED) assert.doesNotThrow(() => rustRegExp(pattern), pattern);
});

test("patterns match what the crate matched, with flag groups or without", () => {
	for (const flagGroups of [true, false]) {
		for (const [pattern, a, b, expected] of MATCHES) {
			assert.equal(same(rustRegExp(pattern, "g", { flagGroups }), a, b), expected, `${JSON.stringify(pattern)} on ${JSON.stringify(a)} (flag groups: ${flagGroups})`);
		}
	}
});

test("Unicode properties JavaScript doesn't have are refused, naming them", () => {
	for (const [pattern, name] of [["\\p{Age=6.0}", "Age"], ["\\p{gcb=Extend}", "Grapheme_Cluster_Break"], ["\\p{wb=ALetter}", "Word_Break"], ["\\p{sb=ATerm}", "Sentence_Break"], ["\\p{Hyphen}", "Hyphen"], ["\\p{Other_Math}", "Other_Math"]]) {
		assert.throws(() => rustRegExp(pattern), new RegExp(`error: Unicode property ${name} isn't in JavaScript's regular expressions$`), pattern);
	}
});

test("a property without regard to case in part of a pattern needs flag groups", () => {
	assert.ok(rustRegExp("(?i)\\p{Lu}").test("a"));
	assert.throws(() => rustRegExp("(?i:\\p{Lu})x", "", { flagGroups: false }), /\n {8}\^{6}\nerror: matching a Unicode property without regard to case in only part of a pattern needs Node 23 or newer; put \(\?i\) at the start of the pattern instead$/);
});

test("Unicode word characters, boundaries and space, as the importer's patterns use them", () => {
	assert.equal(rustRegExp("[A-Za-z_$][\\w$.]*").exec("pluginÉté")?.[0], "pluginÉté");
	assert.deepEqual("--verbosé --x".match(rustRegExp("--?[\\w-]+", "g")), ["--verbosé", "--x"]);
	assert.equal(rustRegExp("é\\b").test("café x"), true);
	assert.equal(rustRegExp("^\\s$").test("\u0085"), true);
	assert.equal(rustRegExp("^\\s$").test("\ufeff"), false);
	assert.equal(rustRegExp("^.$").test("\r"), true);
	assert.equal(rustRegExp("^.$").test("\u2028"), true);
	assert.equal(rustRegExp("(?m)^b").test("a\rb"), false);
	// Capture groups keep their numbers, named or not.
	assert.equal("x.11tydata.json".replace(rustRegExp("\\.11tydata\\.(?P<ext>js|json)$"), ".data.$1"), "x.data.json");
});
